import { useCallback } from 'react';
import { FileSpreadsheet, FileDown, ClipboardCopy, FileText } from 'lucide-react';
import { Button } from '@/components/ui/button';
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu';
import { exportCSV, exportTSV, saveExport } from '@/services/export';
import { computeTotal } from '@/services/balance';
import { computeDailyBalances, groupByMonth } from '@/lib/chart-utils';
import type { TransactionRow } from '../../../shared/ipc-types';

interface ReportExportDropdownProps {
  filteredTransactions: TransactionRow[];
  allTransactions: TransactionRow[];
  startDate: string;
  endDate: string;
  sheetName?: string;
  plannedData?: { description: string; date: string; amount: string; type: string }[];
  onCustomReport: () => void;
}

export function ReportExportDropdown({
  filteredTransactions,
  allTransactions,
  startDate,
  endDate,
  sheetName,
  plannedData,
  onCustomReport,
}: ReportExportDropdownProps) {
  const isEmpty = filteredTransactions.length === 0;

  const handleCSV = useCallback(async () => {
    if (isEmpty) return;
    const content = exportCSV(filteredTransactions, true);
    await saveExport(content, 'report.csv', [{ name: 'CSV', extensions: ['csv'] }]);
  }, [filteredTransactions, isEmpty]);

  const handlePDF = useCallback(async () => {
    if (isEmpty) return;
    const openingBalance = computeTotal(allTransactions.filter((t) => t.date < startDate));
    const now = new Date();
    const { renderReportHTML } = await import('@/services/report-html');
    const balData = computeDailyBalances(allTransactions, startDate, endDate).map((p) => ({
      date: p.dateISO,
      balance: p.balance,
    }));
    const monthData = groupByMonth(filteredTransactions).map((m) => ({
      month: m.month,
      income: m.income,
      expense: m.expense,
    }));
    const generatedStr = `${now.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}, ${now.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })}`;
    const html = renderReportHTML({
      startDate,
      endDate,
      generatedDate: generatedStr,
      sheetName,
      openingBalance,
      includeActivities: true,
      balanceData: balData,
      monthlyData: monthData,
      plannedData,
      transactions: filteredTransactions,
    });
    const pdfBytes = await window.api.printToPDF(html, {
      footerText: `Generated by Fidra \u00b7 ${generatedStr}`,
    });
    const result = await window.api.showSaveDialog({
      title: 'Export PDF',
      defaultPath: 'report.pdf',
      filters: [{ name: 'PDF', extensions: ['pdf'] }],
    });
    if (!result.canceled && result.filePath) {
      await window.api.writeFileBinary(result.filePath, pdfBytes);
    }
  }, [filteredTransactions, allTransactions, startDate, endDate, sheetName, plannedData, isEmpty]);

  const handleClipboard = useCallback(async () => {
    if (isEmpty) return;
    const tsv = exportTSV(filteredTransactions, true);
    await navigator.clipboard.writeText(tsv);
  }, [filteredTransactions, isEmpty]);

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button variant="outline" size="sm" className="h-8 gap-1.5 text-xs">
          <FileDown className="h-3.5 w-3.5" />
          Export
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end">
        <DropdownMenuItem onClick={handleCSV} disabled={isEmpty}>
          <FileSpreadsheet className="h-4 w-4 mr-2" />
          Export as CSV
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handlePDF} disabled={isEmpty}>
          <FileDown className="h-4 w-4 mr-2" />
          Export as PDF
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handleClipboard} disabled={isEmpty}>
          <ClipboardCopy className="h-4 w-4 mr-2" />
          Copy to Clipboard
        </DropdownMenuItem>
        <DropdownMenuSeparator />
        <DropdownMenuItem onClick={onCustomReport}>
          <FileText className="h-4 w-4 mr-2" />
          Custom Report...
        </DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
